# Load dataset
data = load_breast_cancer()
X = data.data
y = np.where(data.target == 0, 1, -1)

# Split dataset
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.3, random_state=42
)

# Feature scaling
scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# Perceptron training
w = np.zeros(X_train.shape[1])
b = 0
alpha = 0.01
epochs = 20
errors_list = []

for ep in range(epochs):
    errors = 0

    for i in range(len(X_train)):
        yin = np.dot(w, X_train[i]) + b

        if yin > 0:
            output = 1
        elif yin < 0:
            output = -1
        else:
            output = 0

        if output != y_train[i]:
            w = w + alpha * y_train[i] * X_train[i]
            b = b + alpha * y_train[i]
            errors += 1

    errors_list.append(errors)
    print("Epoch", ep+1, "Errors:", errors)

# Prediction
y_pred = []

for x in X_test:
    yin = np.dot(w, x) + b

    if yin > 0:
        y_pred.append(1)
    elif yin < 0:
        y_pred.append(-1)
    else:
        y_pred.append(0)

# Accuracy
accuracy = accuracy_score(y_test, y_pred)

print("\nTraining Samples:", len(X_train))
