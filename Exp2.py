import math

def sigmoid(x):
    return 1 / (1 + math.exp(-x))

alpha = 0.25

x1 = 0
x2 = 1
target = 1

# Initial weights
v01, v11, v21 = 0.3, 0.6, -0.1
v02, v12, v22 = 0.5, -0.3, 0.4

w0, w1, w2 = -0.2, 0.4, 0.1

for epoch in range(1, 4):

    # Forward propagation
    zin1 = v01 + x1*v11 + x2*v21
    zin2 = v02 + x1*v12 + x2*v22

    z1 = sigmoid(zin1)
    z2 = sigmoid(zin2)

    yin = w0 + z1*w1 + z2*w2
    y = sigmoid(yin)

    # Error calculation
    error = target - y
    mse = error ** 2

    # Backpropagation
    delta = error * y * (1-y)

    dw1 = alpha * delta * z1
    dw2 = alpha * delta * z2
    dw0 = alpha * delta

    dz1 = delta * w1 * z1 * (1-z1)
    dz2 = delta * w2 * z2 * (1-z2)

    dv11 = alpha * dz1 * x1
    dv21 = alpha * dz1 * x2
    dv01 = alpha * dz1

    dv12 = alpha * dz2 * x1
    dv22 = alpha * dz2 * x2
    dv02 = alpha * dz2

    # Update weights
    v01 += dv01
    v11 += dv11
    v21 += dv21

    v02 += dv02
    v12 += dv12
    v22 += dv22

    w0 += dw0
    w1 += dw1
    w2 += dw2

    print("\nEpoch:", epoch)
    print("Output:", round(y, 4))
    print("Target:", target)
    print("Error:", round(error, 4))
    print("MSE:", round(mse, 4))

    print("Updated Hidden Weights:", v01, v11, v21, v02, v12, v22)
    print("Updated Output Weights:", w0, w1, w2)

print("\nTraining Completed!")

